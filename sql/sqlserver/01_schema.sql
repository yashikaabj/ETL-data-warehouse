-- SQL Server (T-SQL). Creates the source tables in schema [src] of the CURRENT database,
-- so they will not collide with dbo practice tables. Run: USE PHDB; first (or any DB).
IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = 'src') EXEC('CREATE SCHEMA src');
GO
CREATE TABLE src.PHSTATE (
    ID INT NOT NULL DEFAULT 0,
    STATE_NAME VARCHAR(255) NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX ID ON src.PHSTATE(ID);
CREATE INDEX ST_NAME ON src.PHSTATE(STATE_NAME);

CREATE TABLE src.PHHQ (
    HQ_ID INT NOT NULL DEFAULT 0,
    HEAD_QTR VARCHAR(255) NOT NULL DEFAULT '',
    STATE_ID INT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX HQID ON src.PHHQ(HQ_ID);
CREATE INDEX HEADQQTR_STATE ON src.PHHQ(HEAD_QTR, STATE_ID);

CREATE TABLE src.PHPARTY_A (
    CUST_ID INT NOT NULL DEFAULT 0,
    CUST_NAME VARCHAR(255) NOT NULL DEFAULT '',
    HQ_ID INT NOT NULL DEFAULT 0,
    CSBC VARCHAR(255) NOT NULL DEFAULT '',
    BILL_AMOUNT FLOAT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX PHPARTYA_UID ON src.PHPARTY_A(CUST_ID);

CREATE TABLE src.PHITEM (
    ITEM_ID INT NOT NULL DEFAULT 0,
    ITEM_NAME VARCHAR(255) NOT NULL DEFAULT '',
    ITEM_CODE VARCHAR(255) NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX ITEM_ID_CODE ON src.PHITEM(ITEM_ID, ITEM_CODE);
CREATE INDEX ITEM_NAME ON src.PHITEM(ITEM_NAME);

CREATE TABLE src.PHPOSTING (
    POSTING_ID INT NOT NULL DEFAULT 0,
    DOC_TYPE VARCHAR(255) NOT NULL DEFAULT '',
    BILL_AMOUNT FLOAT NOT NULL DEFAULT 0,
    CUST_ID INT NOT NULL DEFAULT 0,
    BILL_NO INT NULL,
    POSTING_DATE DATE NOT NULL            -- added: not in the original DDL
);
CREATE UNIQUE INDEX POSTING_ID ON src.PHPOSTING(POSTING_ID);

CREATE TABLE src.PHPOSTINGDET (
    ITEM_ID INT NOT NULL DEFAULT 0,
    QTY FLOAT NOT NULL DEFAULT 0,
    RATE FLOAT NOT NULL DEFAULT 0,
    AMOUNT FLOAT NOT NULL DEFAULT 0,
    POSTING_ID INT NOT NULL DEFAULT 0,
    POSTINGDET_ID INT NOT NULL DEFAULT 0  -- plain INT (not IDENTITY) so ids load as-is
);
CREATE UNIQUE INDEX POSTING_ID_DETID ON src.PHPOSTINGDET(POSTING_ID, POSTINGDET_ID);

CREATE TABLE src.EMPLOYEE (
    EMP_ID INT NULL,
    EMP_NAME VARCHAR(255) NULL,
    MNGR_ID INT NULL
);
